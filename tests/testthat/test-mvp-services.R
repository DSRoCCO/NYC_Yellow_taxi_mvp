testthat::test_that("el pronóstico respeta el horizonte y no altera la serie", {
  set.seed(1)
  epoch <- seq(as.numeric(as.POSIXct("2024-01-01", tz = "UTC")), by = 3600, length.out = 1000)
  series <- data.frame(epoch = epoch, trips = pmax(0, round(100 + sin(seq_along(epoch) / 8) * 10 + rnorm(1000))))
  model <- fit_series_model(series)
  bundle <- list(series = list(city = series), models = list(city = model))
  out <- forecast_historical(bundle, "city", epoch[900], 24)
  testthat::expect_equal(nrow(out), 24L)
  testthat::expect_true(all(out$epoch > epoch[900]))
  testthat::expect_equal(series$trips, bundle$series$city$trips)
  testthat::expect_error(forecast_historical(bundle, "missing", epoch[900], 24), "serie seleccionada")
  testthat::expect_error(forecast_historical(bundle, "city", NA_real_, 24), "origen histórico válido")
  testthat::expect_error(forecast_historical(bundle, "city", epoch[900], NA_real_), "horizonte debe")
})

testthat::test_that("la proyección futura respeta el límite y genera intervalos", {
  set.seed(2)
  epoch <- seq(as.numeric(as.POSIXct("2022-01-01", tz = "UTC")), by = 3600, length.out = 1000)
  series <- data.frame(epoch = epoch, trips = pmax(0, round(100 + sin(seq_along(epoch) / 8) * 10 + rnorm(1000))))
  model <- fit_series_model(series)
  bundle <- list(series = list(city = series), models = list(city = model))
  out <- forecast_future(bundle, "city", 168)
  testthat::expect_equal(nrow(out), 168L)
  testthat::expect_true(all(out$epoch > max(epoch)))
  testthat::expect_true(all(is.finite(out$prediction)))
  testthat::expect_true(all(out$lower <= out$prediction & out$prediction <= out$upper))
  testthat::expect_error(forecast_future(bundle, "city", 169), "1 y 168")
})

testthat::test_that("el escenario estacional permite fechas futuras acotadas", {
  set.seed(3)
  epoch <- seq(as.numeric(as.POSIXct("2022-01-01", tz = "UTC")), by = 3600, length.out = 1000)
  series <- data.frame(epoch = epoch, trips = pmax(0, round(100 + sin(seq_along(epoch) / 8) * 10 + rnorm(1000))))
  bundle <- list(series = list(city = series), seasonal_models = list(city = fit_seasonal_model(series)))
  out <- seasonal_scenario(bundle, "city", max(epoch) + 24 * 3600)
  testthat::expect_true(out$lower_95 <= out$prediction && out$prediction <= out$upper_95)
  testthat::expect_error(seasonal_scenario(bundle, "city", max(epoch)), "después del corte")
  cone_start <- as.numeric(as.POSIXct(as.Date(as.POSIXct(max(epoch), origin = "1970-01-01", tz = "UTC")) + 1, tz = "UTC"))
  cone <- seasonal_scenario_range(bundle, "city", cone_start, 7)
  testthat::expect_equal(nrow(cone), 7L)
  testthat::expect_true(all(cone$lower_95 <= cone$prediction & cone$prediction <= cone$upper_95))
})
